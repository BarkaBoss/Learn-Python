import re

# --- 1. Common Structures: Error Handler, Symbol Table, Token ---

class ErrorHandler:
    """Manages and reports compilation errors."""
    def __init__(self):
        self.errors = []
        self.had_error = False

    def report(self, stage, message, line=None):
        error_msg = f"[{stage} Error]"
        if line is not None:
            error_msg += f" (Line {line})"
        self.errors.append(f"{error_msg}: {message}")
        self.had_error = True

    def display_errors(self):
        if self.had_error:
            print("\n!!! Compilation Failed with Errors !!!")
            for error in self.errors:
                print(f"  {error}")
        else:
            print("\nCompilation successful! No errors found in the source code.")

class Token:
    """Represents a unit generated by the Lexical Analyzer."""
    def __init__(self, type, value, line):
        self.type = type
        self.value = value
        self.line = line

    def __repr__(self):
        return f"Token({self.type}, '{self.value}', Line {self.line})"

class SymbolTable:
    """Manages variable declarations and attributes (type, value)."""
    def __init__(self):
        # Format: {'var_name': {'type': 'int', 'value': 0}}
        self.symbols = {}

    def add_symbol(self, name, type):
        if name in self.symbols:
            return False # Symbol already exists
        self.symbols[name] = {'type': type, 'value': None}
        return True

    def get_symbol(self, name):
        return self.symbols.get(name)

    def display(self):
        print("\n--- Symbol Table Output ---")
        if not self.symbols:
            print("Symbol Table is empty.")
            return
        print(f"{'Identifier':<15} {'Type':<10} {'Value':<10}")
        print("-" * 35)
        for name, data in self.symbols.items():
            print(f"{name:<15} {data['type']:<10} {str(data['value']):<10}")
        print("-" * 35)


# --- 2. Lexical Analyzer (Scanner) ---

class Lexer:
    """Performs lexical analysis: converts source code into tokens."""
    # Define keywords and token types (Updated: Added 'String')
    KEYWORDS = {'class', 'public', 'static', 'void', 'main', 'int', 'return', 'String'}
    TOKEN_TYPES = {
        'LPAREN': r'\(', 'RPAREN': r'\)',
        'LBRACE': r'\{', 'RBRACE': r'\}',
        'LBRACKET': r'\[', 'RBRACKET': r'\]', # ADDED: Square brackets for array syntax
        'SEMICOLON': r';', 'EQUALS': r'=',
        'PLUS': r'\+', 'MINUS': r'-',
        'INTEGER_LITERAL': r'\b\d+\b',
        'IDENTIFIER': r'[a-zA-Z_][a-zA-Z0-9_]*'
    }

    def __init__(self, source_code, error_handler):
        self.source = source_code
        self.error_handler = error_handler
        self.tokens = []
        self.line_number = 1
        self.position = 0

    def get_next_token(self):
        """Finds the next valid token in the source code."""
        # Skip whitespace and comments
        while self.position < len(self.source):
            char = self.source[self.position]

            if char == '\n':
                self.line_number += 1
                self.position += 1
                continue
            if char.isspace():
                self.position += 1
                continue

            # Simple single-line comment support
            if self.source[self.position:self.position+2] == '//':
                while self.position < len(self.source) and self.source[self.position] != '\n':
                    self.position += 1
                continue

            # Attempt to match all defined token patterns
            for type_name, pattern in self.TOKEN_TYPES.items():
                match = re.match(pattern, self.source[self.position:])
                if match:
                    value = match.group(0)
                    self.position += len(value)

                    # Check for keywords first (they share the IDENTIFIER pattern)
                    if type_name == 'IDENTIFIER' and value in self.KEYWORDS:
                        return Token(value.upper(), value, self.line_number)

                    # Found a match
                    return Token(type_name, value, self.line_number)

            # If loop finishes without returning a token, it's an error
            self.error_handler.report(
                "Lexical Analysis",
                f"Unexpected character: '{char}'",
                self.line_number
            )
            self.position += 1 # Move past the error character
            return None # Return None to skip adding an invalid token

        return Token('EOF', '', self.line_number) # End of file marker

    def scan(self):
        """Processes the entire source code into a list of tokens."""
        print("--- Lexical Analysis Output (Tokens) ---")
        token = self.get_next_token()
        while token and token.type != 'EOF' and not self.error_handler.had_error:
            print(token)
            self.tokens.append(token)
            token = self.get_next_token()

        if token and token.type == 'EOF':
            self.tokens.append(token)

        return self.tokens

# --- 3. Syntax Analyzer (Parser) and AST ---

class ASTNode:
    """Base class for Abstract Syntax Tree nodes."""
    def __init__(self, type, value=None, children=None):
        self.type = type
        self.value = value
        self.children = children if children is not None else []

    def __repr__(self):
        return f"<{self.type}: {self.value}>"

    def print_tree(self, level=0):
        indent = '  ' * level
        print(f"{indent}{self}")
        for child in self.children:
            if isinstance(child, ASTNode):
                child.print_tree(level + 1)
            else:
                print(f"{indent}  {child}")

class Parser:
    """Performs syntax analysis: converts tokens into an AST."""
    def __init__(self, tokens, error_handler):
        self.tokens = tokens
        self.error_handler = error_handler
        self.current = 0

    def peek(self):
        if self.current < len(self.tokens):
            return self.tokens[self.current]
        return self.tokens[-1] # EOF

    def advance(self):
        if self.current < len(self.tokens):
            self.current += 1
        return self.tokens[self.current - 1]

    def match(self, *types):
        """Consumes the current token if it is one of the expected types."""
        if self.peek().type in types:
            return self.advance()
        self.error_handler.report(
            "Syntax Analysis",
            f"Expected one of {types}, found {self.peek().type} ('{self.peek().value}')",
            self.peek().line
        )
        # Attempt to synchronize by skipping to the next semicolon or brace (simple panic mode)
        while self.peek().type not in ('SEMICOLON', 'RBRACE', 'EOF'):
            self.advance()
        if self.peek().type == 'SEMICOLON':
            self.advance()

        return None

    # E -> T (+ | -) E | T
    # T -> F
    # F -> IDENTIFIER | INTEGER_LITERAL | ( E )
    def expression(self):
        """Parses a simple arithmetic expression (E)."""
        left = self.primary()
        while self.peek().type in ('PLUS', 'MINUS'):
            operator = self.advance()
            right = self.primary()
            # Combine the two sides into a binary operation node
            left = ASTNode('BINOP', operator.value, [left, right])
        return left

    def primary(self):
        """Parses the lowest level of an expression (F)."""
        token = self.peek()
        if token.type == 'INTEGER_LITERAL':
            return ASTNode('LITERAL', int(self.advance().value))
        elif token.type == 'IDENTIFIER':
            return ASTNode('VARIABLE', self.advance().value)
        elif token.type == 'LPAREN':
            self.advance() # Consume (
            expr = self.expression()
            self.match('RPAREN') # Consume )
            return expr
        else:
            self.error_handler.report(
                "Syntax Analysis",
                f"Expected identifier, literal, or '(', found {token.type}",
                token.line
            )
            return None

    def statement(self):
        """Parses a single statement (currently only supports variable declaration)."""
        # We check for the starting keyword/token of a statement type
        if self.peek().type == 'INT':
            return self.declaration()

        # If the token is not a recognized statement start, report an error
        self.error_handler.report(
            "Syntax Analysis",
            f"Unexpected token in block: '{self.peek().value}' of type {self.peek().type}. Expected 'int' declaration.",
            self.peek().line
        )
        self.advance() # Advance to try and skip the bad token
        return None


    def block(self):
        """Parses a block of statements (the body between { and })."""
        statements = []
        # Keep parsing statements until we hit the closing brace or EOF
        while self.peek().type not in ('RBRACE', 'EOF'):
            stmt = self.statement()
            if stmt:
                statements.append(stmt)
            else:
                # If statement parsing returned None (due to an unrecoverable error or panic mode),
                # we break to prevent an infinite loop, letting the next match handle the recovery.
                break

        return ASTNode('BLOCK', 'Statement Block', statements)


    def declaration(self):
        """Parses a variable declaration: int id = expression ;"""
        # We only support 'int' as a type keyword for this compiler
        type_token = self.match('INT')
        if not type_token: return None

        name_token = self.match('IDENTIFIER')
        if not name_token: return None

        # Check for assignment part
        assign_node = None
        if self.peek().type == 'EQUALS':
            self.advance() # Consume =
            expr = self.expression()
            if expr:
                assign_node = ASTNode('ASSIGNMENT', '=', [ASTNode('VARIABLE', name_token.value), expr])
            else:
                return None # Expression failed to parse

        self.match('SEMICOLON')

        # The main node is the variable declaration
        children = [ASTNode('TYPE', type_token.value)]
        if assign_node:
            children.append(assign_node)

        return ASTNode('VAR_DECLARATION', name_token.value, children)

    def program(self):
        """Parses the entire source file (simplified main class structure)."""

        # class Main {
        if not self.match('CLASS'): return None
        if not self.match('IDENTIFIER'): return None # Main
        if not self.match('LBRACE'): return None

        # public static void main(String[] args) {
        if not self.match('PUBLIC'): return None
        if not self.match('STATIC'): return None
        if not self.match('VOID'): return None
        if not self.match('MAIN'): return None
        if not self.match('LPAREN'): return None

        # String[] args
        if not self.match('STRING'): return None
        if not self.match('LBRACKET'): return None
        if not self.match('RBRACKET'): return None
        if not self.match('IDENTIFIER'): return None # args

        if not self.match('RPAREN'): return None # )
        if not self.match('LBRACE'): return None # {

        # Parse the block (body of the main method)
        body = self.block()

        self.match('RBRACE') # Close main()
        self.match('RBRACE') # Close class

        if self.peek().type != 'EOF':
             self.error_handler.report("Syntax Analysis", "Expected EOF, found more tokens.", self.peek().line)

        return ASTNode('PROGRAM', 'Main Program', [body])

    def parse(self):
        print("\n--- Syntax Analysis Output (AST) ---")
        ast = self.program()
        if ast and not self.error_handler.had_error:
            ast.print_tree()
        return ast

# --- 4. Semantic Analyzer ---

class SemanticAnalyzer:
    """Checks the AST for semantic correctness (types, scope, usage)."""
    def __init__(self, ast, symbol_table, error_handler):
        self.ast = ast
        self.symbols = symbol_table
        self.error_handler = error_handler
        self.type_map = {'int': 'INT'} # Simple type system

    def check_node(self, node):
        """Recursively checks a single AST node."""
        if not node: return # Handle None nodes from parser errors

        if node.type == 'PROGRAM':
            # Start checking from the program body (BLOCK)
            self.check_node(node.children[0])

        elif node.type == 'BLOCK':
            # Check statements inside the block
            for child in node.children:
                self.check_node(child)

        elif node.type == 'VAR_DECLARATION':
            var_name = node.value
            var_type_node = node.children[0]
            var_type = var_type_node.value

            # 1. Symbol Table Population (Declaration Check)
            if not self.symbols.add_symbol(var_name, var_type):
                self.error_handler.report(
                    "Semantic Analysis",
                    f"Variable '{var_name}' is already declared.",
                    None # We don't have line number in AST yet, simple compiler
                )

            # 2. Assignment Check (if present)
            if len(node.children) > 1 and node.children[1].type == 'ASSIGNMENT':
                assign_node = node.children[1]
                # Check the expression type
                expr_type = self.check_node(assign_node.children[1])

                # Simple Type Check: Ensure expression is compatible with 'int'
                if expr_type and self.type_map.get(var_type) != expr_type:
                    self.error_handler.report(
                        "Semantic Analysis",
                        f"Type mismatch: Cannot assign {expr_type} to '{var_name}' of type {var_type}.",
                        None
                    )
                # Set a mock value in the symbol table for successful assignments
                if expr_type == 'INT':
                     self.symbols.symbols[var_name]['value'] = 'Analyzed' # Placeholder

        elif node.type == 'BINOP':
            # Check left and right operands recursively
            left_type = self.check_node(node.children[0])
            right_type = self.check_node(node.children[1])

            # Simple Type Check: Both operands must be the same (e.g., INT)
            if left_type != right_type:
                self.error_handler.report(
                    "Semantic Analysis",
                    f"Binary operator '{node.value}' requires operands of the same type. Found {left_type} and {right_type}.",
                    None
                )
                return 'ERROR_TYPE'

            # Return the resulting type (e.g., int + int = int)
            return left_type

        elif node.type == 'VARIABLE':
            # 3. Variable Usage Check
            var_name = node.value
            symbol = self.symbols.get_symbol(var_name)
            if not symbol:
                self.error_handler.report(
                    "Semantic Analysis",
                    f"Undeclared variable '{var_name}' used.",
                    None
                )
                return 'ERROR_TYPE'

            # Return the type of the variable
            return self.type_map.get(symbol['type'])

        elif node.type == 'LITERAL':
            # Literal values are assumed to be integers
            return 'INT'

        # This catch-all else case is no longer strictly needed for BLOCK but kept for robustness
        else:
            for child in node.children:
                self.check_node(child)

    def analyze(self):
        print("\n--- Semantic Analysis Output ---")
        if self.ast:
            self.check_node(self.ast)
            print("Semantic analysis completed. See Symbol Table for results.")
        else:
            print("Skipped semantic analysis due to earlier errors.")


# --- 5. Main Compiler Execution ---

def compile_source(source_code):
    """Orchestrates the compiler pipeline."""
    error_handler = ErrorHandler()
    symbol_table = SymbolTable()

    print("===== Starting Compiler Pipeline =====")

    # 1. Lexical Analysis
    lexer = Lexer(source_code, error_handler)
    tokens = lexer.scan()
    if error_handler.had_error:
        error_handler.display_errors()
        return

    # 2. Syntax Analysis
    parser = Parser(tokens, error_handler)
    ast = parser.parse()
    if error_handler.had_error:
        error_handler.display_errors()
        return

    # 3. Semantic Analysis
    semantic_analyzer = SemanticAnalyzer(ast, symbol_table, error_handler)
    semantic_analyzer.analyze()

    # 4. Symbol Table Display and Final Error Handling
    symbol_table.display()
    error_handler.display_errors()


